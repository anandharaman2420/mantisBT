"""
Generates PostgreSQL DDL from the JPA entities (backend/src/main/java/com/mantis/domain/*.java).

This is NOT Hibernate - it is a small parser that mimics what `ddl-auto` produces (table / column names, types, NOT NULL for
primitives and optional=false, identity ids, unique constraints, foreign keys, the many-to-many join table). It is used by the
importer tests so that every column name the importer writes is checked against the real entity definitions.
"""
import glob, os, re

TYPE_SQL = {'Long': 'bigint', 'long': 'bigint', 'int': 'integer', 'Integer': 'integer', 'boolean': 'boolean',
            'Boolean': 'boolean', 'Instant': 'timestamp(6) with time zone', 'byte[]': 'bytea'}
PRIMITIVES = {'int', 'long', 'boolean'}


def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()


def strip_comments(src):
    src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
    return re.sub(r'//[^\n]*', '', src)


def attr(ann, key):
    m = re.search(key + r'\s*=\s*"([^"]*)"', ann)
    return m.group(1) if m else None


def parse_entities(domain_dir):
    entities = {}
    for path in sorted(glob.glob(os.path.join(domain_dir, '*.java'))):
        with open(path, encoding='utf-8') as fh:
            src = strip_comments(fh.read())
        if '@Entity' not in src:
            continue
        cls = re.search(r'public class (\w+)', src).group(1)
        head = src[:src.index('public class')]
        table = attr(head, 'name') if '@Table' in head else snake(cls)
        uniques = [[c.strip().strip('"') for c in m.split(',')]
                   for m in re.findall(r'@UniqueConstraint\(columnNames\s*=\s*\{([^}]*)\}', head)]
        body = src[src.index('{', src.index('public class')) + 1:]
        fields = []
        join_table = None
        for raw in body.split(';'):
            stmt = raw.strip()
            m = re.search(r'private\s+([\w\[\]<>, ]+?)\s+(\w+)\s*(=[^;]*)?$', stmt, re.S)
            if not m:
                continue
            jtype, fname = m.group(1).strip(), m.group(2)
            ann = stmt[:m.start()]
            if '@ManyToMany' in ann:
                jt = re.search(r'@JoinTable\(name\s*=\s*"([^"]+)".*?joinColumns\s*=\s*@JoinColumn\(name\s*=\s*"([^"]+)"\).*?'
                               r'inverseJoinColumns\s*=\s*@JoinColumn\(name\s*=\s*"([^"]+)"\)', ann, re.S)
                join_table = (jt.group(1), jt.group(2), jt.group(3), re.search(r'Set<(\w+)>', jtype).group(1))
                continue
            fields.append(dict(java_type=jtype, name=fname, ann=ann))
        entities[cls] = dict(table=table, uniques=uniques, fields=fields, join=join_table)
    return entities


def generate(domain_dir):
    ents = parse_entities(domain_dir)
    table_of = {c: e['table'] for c, e in ents.items()}
    tables, fks, join_ddl = [], [], []
    for cls, e in ents.items():
        cols = []
        for f in e['fields']:
            ann, jt = f['ann'], f['java_type']
            if '@Id' in ann:
                cols.append(f'{snake(f["name"])} bigint generated by default as identity primary key')
                continue
            if jt in table_of:                                          # many-to-one
                col = attr(ann.split('@JoinColumn')[1], 'name') if '@JoinColumn' in ann else snake(f['name']) + '_id'
                nn = ' not null' if re.search(r'optional\s*=\s*false', ann) else ''
                cols.append(f'{col} bigint{nn}')
                fks.append(f'alter table {e["table"]} add foreign key ({col}) references {table_of[jt]}(id)')
                continue
            col = attr(ann, 'name') if '@Column' in ann and attr(ann, 'name') else snake(f['name'])
            cdef = attr(ann, 'columnDefinition')
            if cdef:
                sql = cdef
            elif jt == 'String':
                ln = re.search(r'length\s*=\s*(\d+)', ann)
                sql = f'varchar({ln.group(1) if ln else 255})'
            else:
                sql = TYPE_SQL[jt]
            nn = jt in PRIMITIVES or re.search(r'nullable\s*=\s*false', ann)
            uq = ' unique' if re.search(r'unique\s*=\s*true', ann) else ''
            cols.append(f'{col} {sql}{uq}{" not null" if nn else ""}')
        for u in e['uniques']:
            cols.append(f'unique ({", ".join(u)})')
        tables.append(f'create table {e["table"]} (\n  ' + ',\n  '.join(cols) + '\n)')
        if e['join']:
            jtable, jcol, icol, target = e['join']
            join_ddl.append(f'create table {jtable} ({jcol} bigint not null references {e["table"]}(id), '
                            f'{icol} bigint not null references {table_of[target]}(id), primary key ({jcol}, {icol}))')
    return tables + join_ddl + fks


if __name__ == '__main__':
    import sys
    print(';\n\n'.join(generate(sys.argv[1])) + ';')
